_MCACHE = {}
def get_model(name):
    if name not in _MCACHE: _MCACHE[name] = SentenceTransformer(name)
    return _MCACHE[name]

def build_dense(chunks, key):
    cfg = EMBEDDING_MODELS[key]; model = get_model(cfg["name"])
    embs = model.encode([cfg["p"]+c["text"] for c in chunks],
                        batch_size=64, normalize_embeddings=True,
                        show_progress_bar=False).astype("float32")
    idx = faiss.IndexFlatIP(embs.shape[1]); idx.add(embs)
    return model, idx, cfg

def dense_search(model, idx, cfg, q, k=10):
    qv = model.encode([cfg["q"]+q], normalize_embeddings=True).astype("float32")
    s, i = idx.search(qv, k)
    return list(zip(i[0].tolist(), s[0].tolist()))

def build_bm25(chunks):
    return BM25Okapi([c["text"].lower().split() for c in chunks])

def bm25_search(bm, q, k=10):
    scores = bm.get_scores(q.lower().split())
    return [(int(i), float(scores[i]))
            for i in np.argsort(scores)[::-1][:k]]

