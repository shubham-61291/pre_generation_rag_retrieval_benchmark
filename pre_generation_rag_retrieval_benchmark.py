_EV_WS = re.compile(r"\s+")
def _n(s): return _EV_WS.sub(" ", s.strip().lower())

def evidence_match(chunk_text, evidence_item, threshold=0.8):
    ct, en = _n(chunk_text), _n(evidence_item)
    if not en: return False
    if en in ct: return True
    et = set(en.split())
    if not et: return False
    return sum(1 for t in et if t in ct) / len(et) >= threshold

def compute_query_metrics(chunks, retrieved_ids, evidence_items, k_list=(1,3,5,10)):
    m = len(evidence_items)
    empty = {f"evidence_recall@{k}": 0.0 for k in k_list}
    empty.update({f"hit@{k}": 0.0 for k in k_list})
    empty.update({f"full@{k}": 0.0 for k in k_list})
    empty.update({"mrr": 0.0, "ndcg@5": 0.0, "ndcg@10": 0.0,
                  "evidence_coverage": 0.0, "n_matched@10": 0})
    if m == 0: return empty

    matches = {}
    for cid in retrieved_ids:
        text = chunks[cid]["text"]
        matches[cid] = {i for i, ev in enumerate(evidence_items)
                        if evidence_match(text, ev)}

    out = {}
    for k in k_list:
        top = retrieved_ids[:k]
        cov = set().union(*[matches[c] for c in top]) if top else set()
        out[f"evidence_recall@{k}"] = len(cov) / m
        out[f"hit@{k}"]  = 1.0 if cov else 0.0
        out[f"full@{k}"] = 1.0 if len(cov) == m else 0.0

    mrr = 0.0
    for r, cid in enumerate(retrieved_ids, 1):
        if matches[cid]: mrr = 1.0 / r; break
    out["mrr"] = mrr

    def ndcg(k):
        dcg, seen = 0.0, set()
        for r, cid in enumerate(retrieved_ids[:k], 1):
            new = matches[cid] - seen
            seen |= new
            dcg += len(new) / np.log2(r + 1)
        idcg = sum(1.0 / np.log2(r + 1) for r in range(1, min(m, k) + 1))
        return dcg / idcg if idcg > 0 else 0.0
    out["ndcg@5"]  = ndcg(5)
    out["ndcg@10"] = ndcg(10)

    cov10 = set().union(*[matches[c] for c in retrieved_ids[:10]]) if retrieved_ids[:10] else set()
    out["evidence_coverage"] = len(cov10) / m
    out["n_matched@10"]      = len(cov10)
    return out

