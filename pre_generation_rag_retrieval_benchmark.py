# --- Query-clustered bootstrap ---
def clustered_bootstrap_ci(g, n_boot=2000, alpha=0.05, seed=0):
    qm = g.groupby("doc_query_key")["recall_10"].mean().values
    n = len(qm)
    if n == 0: return np.nan, np.nan
    rng = np.random.default_rng(seed)
    boots = np.array([qm[rng.integers(0, n, n)].mean() for _ in range(n_boot)])
    return (float(np.percentile(boots, 100*alpha/2)),
            float(np.percentile(boots, 100*(1-alpha/2))))

