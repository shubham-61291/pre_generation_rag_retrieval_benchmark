ENC = tiktoken.get_encoding("cl100k_base")
def ntoks(s): return len(ENC.encode(s))

def chunk_fixed(elements, size=256, overlap=0):
    ids = ENC.encode("\n\n".join(elements))
    step = size - overlap if size > overlap else size
    chunks = []
    for i in range(0, len(ids), step):
        span = ids[i:i + size]
        if not span: break
        chunks.append({"text": ENC.decode(span), "section": None})
        if i + size >= len(ids): break
    return chunks

_SENT = re.compile(r"(?<=[.!?])\s+")
def _to_tokens(block, size):
    out, cur, cur_t = [], [], 0
    for s in _SENT.split(block):
        t = ntoks(s)
        if cur and cur_t + t > size:
            out.append(" ".join(cur)); cur, cur_t = [s], t
        else:
            cur.append(s); cur_t += t
    if cur: out.append(" ".join(cur))
    return out

def chunk_recursive(elements, size=256, overlap=48):
    chunks = []
    for el in elements:
        if ntoks(el) <= size:
            chunks.append({"text": el, "section": None})
        else:
            chunks.extend({"text": p, "section": None} for p in _to_tokens(el, size))
    if overlap > 0 and len(chunks) > 1:
        merged = [chunks[0]]
        for i in range(1, len(chunks)):
            ids = ENC.encode(chunks[i-1]["text"])
            tail = ENC.decode(ids[-overlap:]) if len(ids) > overlap else ""
            merged.append({"text": (tail + " " + chunks[i]["text"]).strip(),
                           "section": None})
        chunks = merged
    return chunks

_TAG_RE = re.compile(r"^\[Section:\s*(.+?)\]\s*\n?(.*)$", re.DOTALL)
def _detect_sections(elements):
    sections, cur_head, cur_body = [], None, []
    def flush():
        if cur_body: sections.append((cur_head, list(cur_body)))
    for el in elements:
        m = _TAG_RE.match(el)
        if m:
            flush()
            head, body = m.group(1).strip(), m.group(2).strip()
            cur_head, cur_body = head, ([body] if body else [])
            continue
        if is_heading(el):
            flush()
            cur_head = el.split("\n", 1)[0].strip()[:120]
            cur_body = [el]
        else:
            cur_body.append(el)
    flush()
    return sections

def chunk_hierarchical(elements, size=256, overlap=32, doc_id=None):
    sections = _detect_sections(elements)
    chunks = []
    for head, body in sections:
        crumb = f"[Doc: {doc_id} | Section: {head}]" if head else f"[Doc: {doc_id}]"
        joined = "\n\n".join(body)
        if ntoks(joined) <= size:
            chunks.append({"text": f"{crumb}\n{joined}", "section": head})
            continue
        ids = ENC.encode(joined)
        step = size - overlap if size > overlap else size
        for i in range(0, len(ids), step):
            span = ids[i:i + size]
            if not span: break
            chunks.append({"text": f"{crumb}\n{ENC.decode(span)}", "section": head})
            if i + size >= len(ids): break
    return chunks

def make_advanced(doc_id):
    return lambda elems: chunk_hierarchical(elems, doc_id=doc_id)

