_WS = re.compile(r"\s+")
def norm(s: str) -> str:
    return _WS.sub(" ", s).strip()

HEADING_RE = re.compile(
    r"^(?:"
    r"(?:CHAPTER|PART|SECTION|SCHEDULE|ANNEXURE)\s+[IVXLC\d\.\-]+"
    r"|(?:Rule|Article|Section|F\.?R\.?)\s*[\dIVXLC\.\-]+"
    r"|\d+\.\d*\s+[A-Z][A-Za-z\s\-&,]{3,90}"
    r"|[A-Z][A-Z\s\-&,\.]{8,90}$"
    r"|#{1,6}\s+[A-Za-z0-9].*"
    r")"
)

def is_heading(text: str) -> bool:
    if not text: return False
    first = text.split("\n", 1)[0].strip()
    if not first or len(first) > 130: return False
    if first.endswith(".") and not re.match(r"^[\dIVXLC]", first): return False
    return bool(HEADING_RE.match(first))

def parse_normal(pages):
    out = []
    for page in pages:
        for p in re.split(r"\n\s*\n", page):
            q = norm(p)
            if len(q) >= 20: out.append(q)
    return out

def parse_context_aware(pages):
    out, current = [], None
    for page in pages:
        for p in re.split(r"\n\s*\n", page):
            if not p.strip(): continue
            if is_heading(p):
                current = p.split("\n", 1)[0].strip()[:120]
                out.append(norm(p))
            else:
                body = norm(p)
                if len(body) < 20: continue
                out.append(f"[Section: {current}]\n{body}" if current else body)
    return out

def parse_docling(path):
    from docling.document_converter import DocumentConverter
    md = DocumentConverter().convert(str(path)).document.export_to_markdown()
    return [b for b in (norm(x) for x in md.split("\n\n")) if len(b) >= 20]

def read_pdf_pages(path):
    return [(p.extract_text() or "") for p in PdfReader(str(path)).pages]

